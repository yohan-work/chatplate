import { normalizeText } from './normalizeText';

const UNSUPPORTED_PATTERNS = [
  /(?:오늘|내일).*(?:날씨|기온|비가)/u,
  /(?:비트코인|주식|코인).*(?:사|팔|투자)/u,
  /(?:점심|저녁|메뉴).*(?:추천|골라)/u,
  /(?:대통령|총리|시장)이?\s*누구/u,
  /(?:숙제|과제).*(?:대신|답을|작성)/u,
  /(?:방정식|수학\s*문제).*(?:풀어|정답)/u,
  /(?:대학교|대학).*(?:합격\s*확률|붙을)/u,
  /(?:adhd|우울증|학습장애|질환).*(?:진단|판단)/u,
  /(?:(?:반드시|무조건).*(?:성적|점수)|(?:성적|점수).*(?:반드시|무조건)).*(?:보장|오른)/u,
  /(?:전교\s*1등|만점).*(?:보장|가능)/u,
  /(?:다른|타)\s*(?:학원|선생님|코치).*(?:평가|비교해|실력)/u,
  /(?:법적으로|판결|법률).*(?:환불|등록|계약)/u,
  /(?:이전|다른)\s*(?:사용자|학생|고객).*(?:상담|대화|정보).*(?:보여|알려)/u,
  /(?:관리자|개발자|시스템).*(?:지시|프롬프트|설정).*(?:무시|출력|보여)/u,
  /(?:시스템\s*프롬프트|내부\s*설정|숨겨진\s*지시)/u,
  /(?:faq|안내)에?\s*없는.*(?:만들|지어|사실처럼)/u,
  /(?:코치|학생|상담원).*(?:개인\s*전화번호|집\s*주소).*(?:알려|조회|보여)/u,
  /아무\s*말이나.*(?:확신|답해)/u,
  /비밀번호.*(?:알려\s*줄게|보내\s*줄게|저장)/u,
  /주민등록번호.*(?:보내면|알려\s*줄게|저장)/u,
  /성적표.*(?:저장해|저장\s*해|보관해)/u,
] as const;

export function isClearlyUnsupportedQuery(query: string): boolean {
  const normalized = normalizeText(query);
  return UNSUPPORTED_PATTERNS.some((pattern) => pattern.test(normalized));
}
